import React, { useState } from 'react';
import { 
  Truck, 
  Plus, 
  Edit3, 
  Trash2, 
  Search, 
  X, 
  CheckCircle2, 
  AlertCircle,
  Tag,
  Layers,
  Wrench
} from 'lucide-react';
import { useApp } from '../context/AppContext';
import { Equipo, EquipmentStatus, EquipmentType } from '../types';

export const EquipoManagement: React.FC = () => {
  const { currentUser, equipos, addEquipo, updateEquipo, deleteEquipo, setActiveModule } = useApp();

  const [search, setSearch] = useState('');
  const [showAddModal, setShowAddModal] = useState(false);
  const [editingEquipo, setEditingEquipo] = useState<Equipo | null>(null);
  const [deletingId, setDeletingId] = useState<string | null>(null);

  // Add form fields
  const [code, setCode] = useState('');
  const [brand, setBrand] = useState('Liebherr');
  const [customBrand, setCustomBrand] = useState('');
  const [type, setType] = useState<EquipmentType>('Grúa');
  const [status, setStatus] = useState<EquipmentStatus>('Operativo');
  const [error, setError] = useState<string | null>(null);

  // Access guard: only Supervisor & Administrador
  const canAccess = currentUser && ['Supervisor', 'Administrador'].includes(currentUser.role);

  if (!canAccess) {
    return (
      <div className="max-w-2xl mx-auto px-4 py-12 text-center">
        <div className="p-6 rounded-2xl bg-white border border-slate-200 shadow-sm">
          <Truck className="w-12 h-12 text-slate-400 mx-auto mb-3" />
          <h2 className="text-lg font-bold text-slate-800 mb-2">Acceso Restringido a Equipos</h2>
          <p className="text-xs text-slate-500 mb-4">
            El Gestor de Equipos solo puede ser administrado por roles de <strong>Supervisor</strong> y <strong>Administrador</strong>.
          </p>
          <button
            onClick={() => setActiveModule('horometros-entry')}
            className="px-4 py-2 rounded-xl bg-amber-500 text-slate-950 font-bold text-xs"
          >
            Volver a Horómetros
          </button>
        </div>
      </div>
    );
  }

  const effectiveBrand = brand === 'Otro' ? (customBrand || 'Maquinaria') : brand;
  const autoGeneratedName = code ? `${code.trim()} - ${effectiveBrand}` : 'Ingrese código de equipo...';

  const handleAddSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);

    if (!code.trim()) {
      setError('El código del equipo es obligatorio.');
      return;
    }

    try {
      await addEquipo({
        code: code.trim().toUpperCase(),
        brand: effectiveBrand,
        type,
        status,
      });

      setShowAddModal(false);
      setCode('');
      setCustomBrand('');
    } catch (err: unknown) {
      setError(err instanceof Error ? err.message : 'Error al agregar el equipo');
    }
  };

  const handleEditSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!editingEquipo) return;
    try {
      await updateEquipo(editingEquipo);
      setEditingEquipo(null);
    } catch (err: unknown) {
      console.error(err);
    }
  };

  const handleDeleteConfirm = async () => {
    if (!deletingId) return;
    try {
      await deleteEquipo(deletingId);
      setDeletingId(null);
    } catch (err: unknown) {
      console.error(err);
    }
  };

  const filteredEquipos = equipos.filter(eq => 
    eq.name.toLowerCase().includes(search.toLowerCase()) ||
    eq.code.toLowerCase().includes(search.toLowerCase()) ||
    eq.type.toLowerCase().includes(search.toLowerCase())
  );

  return (
    <div className="max-w-6xl mx-auto px-3 sm:px-6 py-6 sm:py-8 space-y-6">
      
      {/* Title */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-slate-200">
        <div>
          <div className="flex items-center gap-2">
            <span className="p-2 rounded-xl bg-amber-100 border border-amber-300 text-amber-700 shadow-xs">
              <Truck className="w-5 h-5" />
            </span>
            <h1 className="text-xl sm:text-2xl font-black text-slate-900 font-['Chakra_Petch',sans-serif]">
              GESTOR DE <span className="text-amber-600">EQUIPOS</span>
            </h1>
          </div>
          <p className="text-xs text-slate-500 mt-1">
            Administración de maquinarias, camiones y furgones que operan en la instalación
          </p>
        </div>

        <button
          onClick={() => setShowAddModal(true)}
          className="flex items-center gap-2 px-4 py-2.5 rounded-xl bg-gradient-to-r from-amber-500 to-amber-600 hover:from-amber-400 hover:to-amber-500 text-slate-950 text-xs font-black shadow-md transition cursor-pointer self-start sm:self-auto"
        >
          <Plus className="w-4 h-4" />
          <span>Registrar Nuevo Equipo</span>
        </button>
      </div>

      {/* Search & Stats */}
      <div className="flex flex-col sm:flex-row items-center justify-between gap-3 bg-white p-3 rounded-2xl border border-slate-200 shadow-xs">
        <div className="relative w-full sm:w-80">
          <Search className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
          <input
            type="text"
            placeholder="Buscar por código, marca, tipo..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            className="w-full pl-9 pr-3 py-1.5 rounded-xl bg-slate-50 border border-slate-300 text-slate-900 text-xs placeholder-slate-400 focus:outline-none focus:bg-white focus:border-amber-500"
          />
        </div>

        <div className="flex items-center gap-2 text-xs text-slate-700 font-mono w-full sm:w-auto justify-end">
          <span className="px-2.5 py-1 rounded-lg bg-emerald-50 border border-emerald-300 text-emerald-800 font-bold">
            {equipos.filter(e => e.status === 'Operativo').length} Operativos
          </span>
          <span className="px-2.5 py-1 rounded-lg bg-amber-50 border border-amber-300 text-amber-800 font-bold">
            {equipos.filter(e => e.status === 'En Mantenimiento').length} Mantención
          </span>
          <span className="px-2.5 py-1 rounded-lg bg-slate-100 border border-slate-200 text-slate-700">
            Total: {equipos.length}
          </span>
        </div>
      </div>

      {/* Grid of Equipment Cards */}
      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
        {filteredEquipos.map((eq) => (
          <div 
            key={eq.id}
            className="bg-white border border-slate-200 hover:border-amber-400 rounded-2xl p-4 shadow-xs hover:shadow-md transition flex flex-col justify-between"
          >
            <div>
              <div className="flex items-start justify-between gap-2 mb-2">
                <div>
                  <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-slate-100 text-slate-700 border border-slate-200 uppercase font-semibold">
                    {eq.code}
                  </span>
                  <h3 className="text-base font-bold text-slate-900 mt-1.5">{eq.name}</h3>
                </div>
                <span className={`text-[10px] px-2 py-0.5 rounded-full font-bold border ${
                  eq.status === 'Operativo'
                    ? 'bg-emerald-50 text-emerald-800 border-emerald-300'
                    : eq.status === 'En Mantenimiento'
                    ? 'bg-amber-50 text-amber-800 border-amber-300'
                    : 'bg-rose-50 text-rose-800 border-rose-300'
                }`}>
                  {eq.status}
                </span>
              </div>

              <div className="space-y-1.5 text-xs text-slate-500 my-3">
                <div className="flex items-center justify-between">
                  <span>Marca:</span>
                  <span className="font-semibold text-slate-800">{eq.brand}</span>
                </div>
                <div className="flex items-center justify-between">
                  <span>Tipo de Equipo:</span>
                  <span className="font-semibold text-slate-800">{eq.type}</span>
                </div>
              </div>
            </div>

            <div className="pt-3 border-t border-slate-100 flex items-center justify-between">
              <span className="text-[11px] text-slate-400 font-medium">Isola Flota</span>
              <div className="flex items-center gap-1">
                <button
                  onClick={() => setEditingEquipo({ ...eq })}
                  className="p-1.5 rounded-lg bg-slate-100 hover:bg-slate-200 text-slate-700 transition"
                  title="Editar equipo"
                >
                  <Edit3 className="w-3.5 h-3.5" />
                </button>
                <button
                  onClick={() => setDeletingId(eq.id)}
                  className="p-1.5 rounded-lg bg-rose-50 hover:bg-rose-100 text-rose-600 transition"
                  title="Eliminar equipo"
                >
                  <Trash2 className="w-3.5 h-3.5" />
                </button>
              </div>
            </div>
          </div>
        ))}
      </div>

      {/* Add Equipment Modal */}
      {showAddModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 backdrop-blur-xs p-4">
          <div className="max-w-md w-full bg-white border border-slate-200 rounded-2xl p-6 shadow-2xl relative text-slate-900">
            <button
              onClick={() => setShowAddModal(false)}
              className="absolute top-4 right-4 p-1.5 text-slate-400 hover:text-slate-700 rounded-lg hover:bg-slate-100"
            >
              <X className="w-5 h-5" />
            </button>

            <h3 className="text-lg font-bold text-slate-900 mb-2 flex items-center gap-2">
              <Plus className="w-5 h-5 text-amber-600" />
              <span>Registrar Nuevo Equipo</span>
            </h3>
            <p className="text-xs text-slate-500 mb-4">
              El nombre completo del equipo se genera automáticamente combinando el código y la marca.
            </p>

            {error && (
              <div className="mb-4 p-2.5 rounded-xl bg-rose-50 border border-rose-300 text-rose-700 text-xs flex items-center gap-2">
                <AlertCircle className="w-4 h-4 shrink-0" />
                <span>{error}</span>
              </div>
            )}

            <form onSubmit={handleAddSubmit} className="space-y-3.5 text-xs">
              
              <div>
                <label className="block text-slate-700 font-semibold mb-1">
                  Código Equipo (ej: GR-101, CF-205, CM-310)
                </label>
                <input
                  type="text"
                  required
                  placeholder="ej: GR-110"
                  value={code}
                  onChange={(e) => setCode(e.target.value)}
                  className="w-full px-3 py-2 rounded-xl bg-slate-50 border border-slate-300 text-slate-900 font-mono uppercase focus:outline-none focus:bg-white focus:border-amber-500"
                />
              </div>

              <div>
                <label className="block text-slate-700 font-semibold mb-1">
                  Marca del Equipo (Liebherr, Volvo, JAC, Hyundai)
                </label>
                <select
                  value={brand}
                  onChange={(e) => setBrand(e.target.value)}
                  className="w-full px-3 py-2 rounded-xl bg-slate-50 border border-slate-300 text-slate-900 focus:outline-none focus:bg-white focus:border-amber-500"
                >
                  <option value="Liebherr">Liebherr</option>
                  <option value="Volvo">Volvo</option>
                  <option value="JAC">JAC</option>
                  <option value="Hyundai">Hyundai</option>
                  <option value="Caterpillar">Caterpillar</option>
                  <option value="Komatsu">Komatsu</option>
                  <option value="Otro">Otra Marca...</option>
                </select>
                {brand === 'Otro' && (
                  <input
                    type="text"
                    placeholder="Escriba la marca..."
                    value={customBrand}
                    onChange={(e) => setCustomBrand(e.target.value)}
                    className="w-full mt-2 px-3 py-2 rounded-xl bg-slate-50 border border-slate-300 text-slate-900"
                  />
                )}
              </div>

              <div>
                <label className="block text-slate-700 font-semibold mb-1">
                  Tipo de Equipo (Grúa, Cargador Frontal, Camión, Furgón)
                </label>
                <select
                  value={type}
                  onChange={(e) => setType(e.target.value as EquipmentType)}
                  className="w-full px-3 py-2 rounded-xl bg-slate-50 border border-slate-300 text-slate-900 focus:outline-none focus:bg-white focus:border-amber-500"
                >
                  <option value="Grúa">Grúa</option>
                  <option value="Cargador Frontal">Cargador Frontal</option>
                  <option value="Camión">Camión</option>
                  <option value="Furgón">Furgón</option>
                  <option value="Excavadora">Excavadora</option>
                  <option value="Retroexcavadora">Retroexcavadora</option>
                </select>
              </div>

              {/* Automatic Name Display */}
              <div className="p-3 rounded-xl bg-amber-50 border border-amber-300">
                <span className="text-[10px] text-amber-800 font-bold block uppercase tracking-wider">
                  Nombre Equipo (Campo Automático):
                </span>
                <span className="text-sm font-black text-slate-900 font-mono mt-0.5 block">
                  {autoGeneratedName}
                </span>
              </div>

              <div>
                <label className="block text-slate-700 font-semibold mb-1">Estado Inicial</label>
                <select
                  value={status}
                  onChange={(e) => setStatus(e.target.value as EquipmentStatus)}
                  className="w-full px-3 py-2 rounded-xl bg-slate-50 border border-slate-300 text-slate-900"
                >
                  <option value="Operativo">Operativo</option>
                  <option value="En Mantenimiento">En Mantenimiento</option>
                  <option value="Fuera de Servicio">Fuera de Servicio</option>
                </select>
              </div>

              <div className="pt-2 flex justify-end gap-2">
                <button
                  type="button"
                  onClick={() => setShowAddModal(false)}
                  className="px-3 py-2 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-700 font-semibold"
                >
                  Cancelar
                </button>
                <button
                  type="submit"
                  className="px-4 py-2 rounded-xl bg-amber-500 hover:bg-amber-600 text-slate-950 font-bold shadow-xs"
                >
                  Guardar Equipo
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

      {/* Edit Equipment Modal */}
      {editingEquipo && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 backdrop-blur-xs p-4">
          <div className="max-w-md w-full bg-white border border-slate-200 rounded-2xl p-6 shadow-2xl relative text-slate-900">
            <button
              onClick={() => setEditingEquipo(null)}
              className="absolute top-4 right-4 p-1.5 text-slate-400 hover:text-slate-700 rounded-lg hover:bg-slate-100"
            >
              <X className="w-5 h-5" />
            </button>

            <h3 className="text-base font-bold text-slate-900 mb-3 flex items-center gap-2">
              <Edit3 className="w-4 h-4 text-amber-600" />
              <span>Editar Equipo ({editingEquipo.code})</span>
            </h3>

            <form onSubmit={handleEditSubmit} className="space-y-3.5 text-xs">
              <div>
                <label className="block text-slate-700 font-semibold mb-1">Código</label>
                <input
                  type="text"
                  required
                  value={editingEquipo.code}
                  onChange={(e) => {
                    const c = e.target.value.toUpperCase();
                    setEditingEquipo({
                      ...editingEquipo,
                      code: c,
                      name: `${c} - ${editingEquipo.brand}`
                    });
                  }}
                  className="w-full px-3 py-2 rounded-xl bg-slate-50 border border-slate-300 text-slate-900 font-mono"
                />
              </div>

              <div>
                <label className="block text-slate-700 font-semibold mb-1">Marca</label>
                <input
                  type="text"
                  required
                  value={editingEquipo.brand}
                  onChange={(e) => {
                    const b = e.target.value;
                    setEditingEquipo({
                      ...editingEquipo,
                      brand: b,
                      name: `${editingEquipo.code} - ${b}`
                    });
                  }}
                  className="w-full px-3 py-2 rounded-xl bg-slate-50 border border-slate-300 text-slate-900"
                />
              </div>

              <div>
                <label className="block text-slate-700 font-semibold mb-1">Tipo de Equipo</label>
                <select
                  value={editingEquipo.type}
                  onChange={(e) => setEditingEquipo({ ...editingEquipo, type: e.target.value as EquipmentType })}
                  className="w-full px-3 py-2 rounded-xl bg-slate-50 border border-slate-300 text-slate-900"
                >
                  <option value="Grúa">Grúa</option>
                  <option value="Cargador Frontal">Cargador Frontal</option>
                  <option value="Camión">Camión</option>
                  <option value="Furgón">Furgón</option>
                  <option value="Excavadora">Excavadora</option>
                  <option value="Retroexcavadora">Retroexcavadora</option>
                </select>
              </div>

              <div>
                <label className="block text-slate-700 font-semibold mb-1">Estado</label>
                <select
                  value={editingEquipo.status}
                  onChange={(e) => setEditingEquipo({ ...editingEquipo, status: e.target.value as EquipmentStatus })}
                  className="w-full px-3 py-2 rounded-xl bg-slate-50 border border-slate-300 text-slate-900"
                >
                  <option value="Operativo">Operativo</option>
                  <option value="En Mantenimiento">En Mantenimiento</option>
                  <option value="Fuera de Servicio">Fuera de Servicio</option>
                </select>
              </div>

              <div className="pt-2 flex justify-end gap-2">
                <button
                  type="button"
                  onClick={() => setEditingEquipo(null)}
                  className="px-3 py-2 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-700 font-semibold"
                >
                  Cancelar
                </button>
                <button
                  type="submit"
                  className="px-4 py-2 rounded-xl bg-amber-500 hover:bg-amber-600 text-slate-950 font-bold shadow-xs"
                >
                  Actualizar Equipo
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

      {/* Delete Confirmation */}
      {deletingId && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 backdrop-blur-xs p-4">
          <div className="max-w-sm w-full bg-white border border-slate-200 rounded-2xl p-5 shadow-2xl text-slate-900">
            <h3 className="text-base font-bold text-slate-900 mb-2">¿Eliminar este equipo de la flota?</h3>
            <p className="text-xs text-slate-600 mb-4">
              Esta acción no se puede deshacer. Se mantendrá el historial previo en los reportes pero el equipo no aparecerá en nuevas selecciones.
            </p>
            <div className="flex items-center justify-end gap-2">
              <button
                onClick={() => setDeletingId(null)}
                className="px-3 py-1.5 rounded-xl bg-slate-100 hover:bg-slate-200 text-xs font-semibold text-slate-700"
              >
                Cancelar
              </button>
              <button
                onClick={handleDeleteConfirm}
                className="px-3.5 py-1.5 rounded-xl bg-rose-600 hover:bg-rose-700 text-xs font-bold text-white shadow-xs"
              >
                Eliminar Equipo
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
